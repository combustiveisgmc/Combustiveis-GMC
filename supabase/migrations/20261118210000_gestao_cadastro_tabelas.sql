-- Cadastros do portal como tabelas (18/11/2026, pedido do usuário: "quero que sejam tabelas no banco de dados e que sejam cadastros
-- que estejam em todo o portal, por exemplo o carro e o motorista estão em uma unidade X que essa unidade seja uma característica
-- de cadastro"). Antes eram listas de texto na engrenagem dos cadastros (D1 opcoes_cadastro).
--
-- Esquema `cadastro` = ORIGEM (editado pelo portal). Ele não é apagado pela carga do modelo (scripts/gestao_carga.py apaga e refaz o
-- esquema gestao a cada 5 min a partir das planilhas); a carga lê daqui: gestao.unidades sai com o MESMO id de cadastro.unidades
-- (veículos, motoristas, abastecimentos... apontam para a unidade pelo id), e os nomes antigos das planilhas chegam pelos apelidos.

create schema if not exists cadastro;

create table if not exists cadastro.unidades (
  id            integer generated by default as identity primary key,
  nome          text not null unique,               -- como no centro de custo (INFORMAÇÃO ADICIONAL 3): RAJA JEQUIE
  nome_curto    text,                               -- como no orçamento: Jequié
  centro_custo  text unique,                        -- código Protheus
  empresa       text not null default 'RAJA LOG' check (empresa in ('RAJA LOG', 'KEMIGAS')),
  operacional   boolean not null default true,      -- false: ADM, DIRETORIA, retiradas
  ativa         boolean not null default true,      -- desativada: some das listas dos formulários; quem já tem continua tendo
  criado_em     timestamptz not null default now(),
  atualizado_em timestamptz not null default now()
);
create table if not exists cadastro.unidade_apelidos (   -- outros jeitos de escrever (planilhas) e nomes antigos (renomear)
  apelido     text primary key,                         -- gestao.chave(): sem acento, maiúsculo
  unidade_id  integer not null references cadastro.unidades(id) on delete cascade,
  origem      text
);
create table if not exists cadastro.categorias_veiculo (
  id integer generated by default as identity primary key, nome text not null unique, ativa boolean not null default true,
  criado_em timestamptz not null default now()
);
create table if not exists cadastro.marcas_veiculo (
  id integer generated by default as identity primary key, nome text not null unique, ativa boolean not null default true,
  criado_em timestamptz not null default now()
);
create table if not exists cadastro.avisos_posto (          -- aviso que aparece no posto (lista dos motoristas)
  id integer generated by default as identity primary key, nome text not null unique, ativa boolean not null default true,
  criado_em timestamptz not null default now()
);
create table if not exists cadastro.produtos_contrato (     -- produto dos contratos x ANP
  id integer generated by default as identity primary key, nome text not null unique, ativa boolean not null default true,
  criado_em timestamptz not null default now()
);
alter table cadastro.unidades enable row level security;
alter table cadastro.unidade_apelidos enable row level security;
alter table cadastro.categorias_veiculo enable row level security;
alter table cadastro.marcas_veiculo enable row level security;
alter table cadastro.avisos_posto enable row level security;
alter table cadastro.produtos_contrato enable row level security;

-- carga inicial: o que o modelo já tem hoje (mesmos ids das unidades)
insert into cadastro.unidades (id, nome, nome_curto, centro_custo, empresa, operacional, ativa)
  select u.id, u.nome, u.nome_curto, u.centro_custo, coalesce(e.nome, 'RAJA LOG'), u.operacional, u.ativa
  from gestao.unidades u left join gestao.empresas e on e.id = u.empresa_id
  on conflict do nothing;
select setval(pg_get_serial_sequence('cadastro.unidades', 'id'), greatest((select max(id) from cadastro.unidades), 1));
insert into cadastro.unidade_apelidos (apelido, unidade_id, origem)
  select a.apelido, a.unidade_id, a.origem from gestao.unidade_apelidos a
  where exists (select 1 from cadastro.unidades u where u.id = a.unidade_id)
  on conflict do nothing;
insert into cadastro.categorias_veiculo (nome)
  select distinct upper(trim(categoria)) from gestao.veiculos where cadastrado and nullif(trim(categoria), '') is not null
  on conflict do nothing;
insert into cadastro.marcas_veiculo (nome)
  select distinct upper(trim(marca)) from gestao.veiculos where cadastrado and nullif(trim(marca), '') is not null
  on conflict do nothing;

-- ---------- leitura e gravação pelo portal (Functions da Cloudflare, chave secreta) ----------
create or replace function public.gestao_cadastro_listas() returns jsonb language sql stable security definer set search_path = cadastro, public as $$
  select jsonb_build_object(
    'unidade', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'nome_curto', nome_curto, 'centro_custo', centro_custo,
      'empresa', empresa, 'operacional', operacional, 'ativa', ativa) order by nome) from cadastro.unidades), '[]'::jsonb),
    'categoria', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'ativa', ativa) order by nome) from cadastro.categorias_veiculo), '[]'::jsonb),
    'marca', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'ativa', ativa) order by nome) from cadastro.marcas_veiculo), '[]'::jsonb),
    'aviso', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'ativa', ativa) order by nome) from cadastro.avisos_posto), '[]'::jsonb),
    'produto', coalesce((select jsonb_agg(jsonb_build_object('id', id, 'nome', nome, 'ativa', ativa) order by nome) from cadastro.produtos_contrato), '[]'::jsonb))
$$;

-- p_tipo: unidade | categoria | marca | aviso | produto
-- p_acao: adicionar (p_dados.nome) | renomear (p_id, p_dados.nome) | ativar | desativar (p_id) | editar (unidade: nome_curto, centro_custo,
--         empresa, operacional)
-- Nome repetido (sem diferença de acento/maiúscula) é recusado. Renomear unidade guarda o nome antigo como apelido (planilhas antigas).
create or replace function public.gestao_cadastro_salvar(p_tipo text, p_acao text, p_id integer, p_dados jsonb)
returns jsonb language plpgsql security definer set search_path = cadastro, gestao, public as $$
declare
  tabela text := case p_tipo when 'unidade' then 'unidades' when 'categoria' then 'categorias_veiculo' when 'marca' then 'marcas_veiculo'
                   when 'aviso' then 'avisos_posto' when 'produto' then 'produtos_contrato' end;
  nome text := nullif(regexp_replace(trim(coalesce(p_dados->>'nome', '')), '\s+', ' ', 'g'), '');
  antigo text; novo_id integer; repetido integer;
begin
  if tabela is null then return jsonb_build_object('ok', false, 'erro', 'Cadastro desconhecido.'); end if;
  -- unidade, categoria e marca em maiúsculas (como nas planilhas e no centro de custo)
  if nome is not null and p_tipo in ('unidade', 'categoria', 'marca') then nome := upper(nome); end if;
  if nome is not null and length(nome) > 80 then return jsonb_build_object('ok', false, 'erro', 'Nome com mais de 80 caracteres.'); end if;

  if p_acao in ('adicionar', 'renomear') then
    if nome is null then return jsonb_build_object('ok', false, 'erro', 'Escreva o nome.'); end if;
    execute format('select id from cadastro.%I where gestao.chave(nome) = gestao.chave($1) and ($2::integer is null or id <> $2) limit 1', tabela)
      into repetido using nome, p_id;
    if repetido is not null then return jsonb_build_object('ok', false, 'erro', nome || ' já está cadastrado.'); end if;
    if p_tipo = 'unidade' then
      select unidade_id into repetido from cadastro.unidade_apelidos where apelido = gestao.chave(nome) and unidade_id is distinct from p_id;
      if repetido is not null then
        return jsonb_build_object('ok', false, 'erro', nome || ' já é outro nome da unidade ' || (select u.nome from cadastro.unidades u where u.id = repetido) || '.');
      end if;
    end if;
  end if;

  if p_acao = 'adicionar' then
    if p_tipo = 'unidade' then
      insert into cadastro.unidades (nome, nome_curto, centro_custo, empresa, operacional)
        values (nome, nullif(trim(p_dados->>'nome_curto'), ''), nullif(trim(p_dados->>'centro_custo'), ''),
                case when upper(coalesce(p_dados->>'empresa', '')) = 'KEMIGAS' or nome like 'KEMIGAS%' then 'KEMIGAS' else 'RAJA LOG' end,
                coalesce((p_dados->>'operacional')::boolean, true))
        returning id into novo_id;
      insert into cadastro.unidade_apelidos (apelido, unidade_id, origem) values (gestao.chave(nome), novo_id, 'portal') on conflict do nothing;
    else
      execute format('insert into cadastro.%I (nome) values ($1) returning id', tabela) into novo_id using nome;
    end if;
    return jsonb_build_object('ok', true, 'id', novo_id);
  end if;

  if p_id is null then return jsonb_build_object('ok', false, 'erro', 'Item inválido.'); end if;
  execute format('select nome from cadastro.%I where id = $1', tabela) into antigo using p_id;
  if antigo is null then return jsonb_build_object('ok', false, 'erro', 'Este item não existe mais. Recarregue a página.'); end if;

  if p_acao = 'renomear' then
    execute format('update cadastro.%I set nome = $1 where id = $2', tabela) using nome, p_id;
    if p_tipo = 'unidade' then   -- o modelo gestao recebe o nome novo na próxima carga (5 min); o antigo continua achando a unidade
      update cadastro.unidades set atualizado_em = now() where id = p_id;
      insert into cadastro.unidade_apelidos (apelido, unidade_id, origem) values (gestao.chave(antigo), p_id, 'nome antigo')
        on conflict (apelido) do update set unidade_id = excluded.unidade_id;
      insert into cadastro.unidade_apelidos (apelido, unidade_id, origem) values (gestao.chave(nome), p_id, 'portal')
        on conflict (apelido) do update set unidade_id = excluded.unidade_id;
    end if;
  elsif p_acao in ('ativar', 'desativar') then
    execute format('update cadastro.%I set ativa = $1 where id = $2', tabela) using (p_acao = 'ativar'), p_id;
  elsif p_acao = 'editar' and p_tipo = 'unidade' then
    if nullif(trim(p_dados->>'centro_custo'), '') is not null and exists (select 1 from cadastro.unidades
         where centro_custo = trim(p_dados->>'centro_custo') and id <> p_id) then
      return jsonb_build_object('ok', false, 'erro', 'Este centro de custo já é de outra unidade.');
    end if;
    update cadastro.unidades set
      nome_curto = case when p_dados ? 'nome_curto' then nullif(trim(p_dados->>'nome_curto'), '') else nome_curto end,
      centro_custo = case when p_dados ? 'centro_custo' then nullif(trim(p_dados->>'centro_custo'), '') else centro_custo end,
      empresa = case when upper(coalesce(p_dados->>'empresa', '')) in ('RAJA LOG', 'KEMIGAS') then upper(p_dados->>'empresa') else empresa end,
      operacional = coalesce((p_dados->>'operacional')::boolean, operacional),
      atualizado_em = now()
    where id = p_id;
  else
    return jsonb_build_object('ok', false, 'erro', 'Ação desconhecida.');
  end if;
  return jsonb_build_object('ok', true, 'id', p_id);
end $$;

-- unidade pelo nome ou apelido, no CADASTRO. Antes criava uma unidade nova quando o nome não existia; agora não cria (devolve null
-- e quem grava recusa). O id é o mesmo em cadastro e gestao.
create or replace function gestao.unidade_id(nome text) returns integer language sql stable as $$
  select coalesce(
    (select u.id from cadastro.unidades u where gestao.chave(u.nome) = gestao.chave(nome)),
    (select a.unidade_id from cadastro.unidade_apelidos a where a.apelido = gestao.chave(nome)))
$$;

-- placa: unidade, categoria e marca têm de estar no cadastro (antes aceitava qualquer texto e criava unidade). null = tudo certo.
create or replace function public.gestao_validar_placa(p_dados jsonb) returns text language plpgsql stable security definer
set search_path = cadastro, gestao, public as $$
begin
  if nullif(trim(coalesce(p_dados->>'unidade', '')), '') is not null and gestao.unidade_id(p_dados->>'unidade') is null then
    return 'A unidade ' || upper(trim(p_dados->>'unidade')) || ' não está cadastrada. Cadastre na engrenagem do formulário.';
  end if;
  if nullif(trim(coalesce(p_dados->>'categoria', '')), '') is not null
     and not exists (select 1 from cadastro.categorias_veiculo where gestao.chave(nome) = gestao.chave(p_dados->>'categoria')) then
    return 'A categoria ' || upper(trim(p_dados->>'categoria')) || ' não está cadastrada. Cadastre na engrenagem do formulário.';
  end if;
  if nullif(trim(coalesce(p_dados->>'marca', '')), '') is not null
     and not exists (select 1 from cadastro.marcas_veiculo where gestao.chave(nome) = gestao.chave(p_dados->>'marca')) then
    return 'A marca ' || upper(trim(p_dados->>'marca')) || ' não está cadastrada. Cadastre na engrenagem do formulário.';
  end if;
  return null;
end $$;

-- gravar placa: a mesma de 17/11 (20261117110000_gestao_site_placas.sql), com a validação acima no começo
create or replace function public.gestao_salvar_placa(p_acao text, p_chave text, p_dados jsonb) returns jsonb
language plpgsql security definer set search_path = gestao, public as $$
declare
  atual text := upper(regexp_replace(coalesce(p_chave, ''), '[^A-Za-z0-9]', '', 'g'));
  nova text := upper(regexp_replace(coalesce(p_dados->>'placa', p_chave, ''), '[^A-Za-z0-9]', '', 'g'));
  vid integer;
  sit text := case upper(coalesce(p_dados->>'situacao', '')) when 'DESABILITADA' then 'desabilitado' when 'VENDIDO' then 'vendido'
                when 'ATIVA' then 'ativo' else null end;
  invalido text := public.gestao_validar_placa(p_dados);
begin
  if invalido is not null then return jsonb_build_object('ok', false, 'erro', invalido); end if;
  if p_acao = 'adicionar' then
    select id into vid from gestao.veiculos where placa = nova;
    if vid is null then
      insert into gestao.veiculos (placa, situacao, cadastrado) values (nova, coalesce(sit, 'ativo'), true) returning id into vid;
    else
      update gestao.veiculos set cadastrado = true where id = vid;
    end if;
  else
    select id into vid from gestao.veiculos where placa = atual;
    if vid is null then return jsonb_build_object('ok', false, 'erro', 'placa ' || atual || ' não está no banco'); end if;
    if nova <> atual then update gestao.veiculos set placa = nova where id = vid; end if;
  end if;
  update gestao.veiculos set
    categoria = case when p_dados ? 'categoria' then nullif(upper(trim(p_dados->>'categoria')), '') else categoria end,
    unidade_id = case when p_dados ? 'unidade' then gestao.unidade_id(p_dados->>'unidade') else unidade_id end,
    marca = case when p_dados ? 'marca' then nullif(upper(trim(p_dados->>'marca')), '') else marca end,
    modelo = case when p_dados ? 'modelo' then nullif(trim(p_dados->>'modelo'), '') else modelo end,
    ano_fabricacao = case when p_dados ? 'ano' then nullif(p_dados->>'ano', '')::numeric::smallint else ano_fabricacao end,
    meta_km_l = case when p_dados ? 'meta' then nullif(p_dados->>'meta', '')::numeric else meta_km_l end,
    capacidade_tanque_l = case when p_dados ? 'capTanque' then nullif(p_dados->>'capTanque', '')::numeric else capacidade_tanque_l end,
    situacao = coalesce(sit, situacao),
    atualizado_em = now()
  where id = vid;
  -- as fórmulas da planilha: ponto crítico = meta - 0,5; autonomia = tanque x meta x 0,75
  update gestao.veiculos set
    ponto_critico_km_l = case when meta_km_l > 0 then meta_km_l - 0.5 end,
    autonomia_km = case when meta_km_l > 0 and capacidade_tanque_l > 0 then capacidade_tanque_l * meta_km_l * 0.75 end
  where id = vid;
  return jsonb_build_object('ok', true, 'id', vid);
end $$;

